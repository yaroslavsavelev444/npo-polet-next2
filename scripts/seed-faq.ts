/**
 * Минимальный документ Lexical из набора абзацев.
 *
 * `as const` на строковых литералах обязателен: сгенерированные Payload типы
 * объявляют `format` не строкой, а объединением ("" | "left" | "center" | …).
 * Без уточнения TypeScript выводит просто string, и вызов payload.create не
 * проходит проверку типов.
 */
function richText(paragraphs: string[]) {
	return {
		root: {
			type: "root",
			format: "" as const,
			indent: 0,
			version: 1,
			direction: "ltr" as const,
			children: paragraphs.map((text) => ({
				type: "paragraph",
				format: "" as const,
				indent: 0,
				version: 1,
				direction: "ltr" as const,
				textFormat: 0,
				children: [
					{
						type: "text",
						text,
						format: 0,
						style: "",
						mode: "normal",
						detail: 0,
						version: 1,
					},
				],
			})),
		},
	};
}

