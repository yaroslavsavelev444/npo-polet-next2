async function main() {
	const payload = await getPayload({ config });

	for (const topic of TOPICS) {
		const existing = await payload.find({
			collection: "faq",
			where: { slug: { equals: topic.slug } },
			limit: 1,
			overrideAccess: true,
		});

		const data = {
			title: topic.title,
			slug: topic.slug,
			description: topic.description,
			order: topic.order,
			isActive: true,
			questions: topic.questions.map((question, index) => ({
				question: question.question,
				answer: richText(question.answer),
				isFeatured: Boolean(question.isFeatured),
				isActive: true,
				order: (index + 1) * 10,
			})),
		};

		if (existing.docs.length > 0) {
			await payload.update({
				collection: "faq",
				id: existing.docs[0].id,
				data,
				overrideAccess: true,
			});
			console.log(`обновлена тема: ${topic.title}`);
		} else {
			await payload.create({
				collection: "faq",
				data,
				overrideAccess: true,
			});
			console.log(`создана тема:   ${topic.title}`);
		}
	}

	const featured = TOPICS.flatMap((topic) =>
		topic.questions.filter((question) => question.isFeatured),
	).length;
	const total = TOPICS.reduce((sum, topic) => sum + topic.questions.length, 0);

	console.log(
		`\nГотово: тем ${TOPICS.length}, вопросов ${total}, из них на главной ${featured}.`,
	);
	console.log(
		'Ответы с пометкой "[ЗАПОЛНИТЬ]" нужно заменить реальными данными в админке.',
	);

	process.exit(0);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
