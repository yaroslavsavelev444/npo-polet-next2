// app/robots.ts
import type { MetadataRoute } from "next";
import { baseURL } from "@/resources/content";

export default function robots(): MetadataRoute.Robots {
	return {
		rules: [
			{
				userAgent: "*",
				// Файлы медиатеки Payload отдаются из-под /api (/api/media/file/…),
				// поэтому общий запрет /api/ закрывал от роботов ВСЕ изображения
				// товаров: og:image, image в JSON-LD Product и логотип Organization.
				// Google требует, чтобы картинка из Product была доступна для
				// сканирования, иначе товар не получает расширенный сниппет, а сами
				// изображения не попадают в поиск по картинкам. Разрешение длиннее
				// запрета, поэтому и Google, и Яндекс (оба выбирают самое длинное
				// совпавшее правило) применяют его, а остальной /api/ остаётся
				// закрытым.
				allow: ["/", "/api/media/file/"],
				disallow: [
					"/admin",
					"/admin/*",
					"/api/",
					"/auth/",
					"/cart",
					"/checkout",
					"/profile",
					"/profile/*",
					"/orders",
					"/orders/*",
					"/wishlist",
					"/*?*group=",
					// Отфильтрованная выдача базы знаний: то же содержимое в другой
					// нарезке. Сами материалы при этом полностью открыты — робот
					// доходит до них с /knowledge и из sitemap.
					"/knowledge?*",
					// Фасетная выдача каталога (производитель, скидка,
					// характеристики): число комбинаций — произведение числа
					// значений, и обход их всех съел бы бюджет сканирования на
					// дубли раздела. Сам раздел и его сортировки/цена открыты;
					// на случай, если фасетный адрес всё же найден, у него
					// canonical на раздел (см. page.tsx категории).
					"/category/*?*brand=",
					"/category/*?*discount=",
					"/category/*?*f.",
				],
			},
		],
		sitemap: `${baseURL}/sitemap.xml`,
		// Host понимает только Яндекс (Google пропускает неизвестные поля) —
		// оставлен ради существующей настройки в Вебмастере.
		host: baseURL,
	};
}
