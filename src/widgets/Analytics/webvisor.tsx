import type { ReactNode } from "react";

/**
 * Что Вебвизор Яндекс.Метрики не должен записывать.
 *
 * Вебвизор пишет страницу целиком: тексты, а при настройке «Записывать все
 * поля» — и ввод. Это уходит в Яндекс, а у нас в Согласии Метрика — только
 * аналитика без содержимого форм. Поэтому:
 *
 *  • ym-disable-keys стоит на <body>: ввод не записывается ни в одном поле
 *    сайта — форма входа, оформление, профиль, поиск, чат, обратная связь,
 *    включая модалки (они порталом в том же <body>);
 *  • ym-hide-content — на экранах и виджетах, где показываются данные
 *    покупателя (ФИО, телефоны, адреса, заказы, переписка): в записи вместо
 *    содержимого пусто.
 *
 * Классы Метрики действуют на элемент и всех потомков
 * (https://yandex.ru/support/metrica/ru/code/html-markup). Маршрутом это не
 * решить: счётчик инициализируется один раз, переходы — клиентские, и запись,
 * начатая на главной, продолжилась бы на /checkout.
 */
export const WEBVISOR_NO_KEYS = "ym-disable-keys";
export const WEBVISOR_HIDE = "ym-hide-content";

/**
 * Обёртка «не записывать содержимое». display: contents — в раскладке её нет,
 * дети ведут себя так, будто лежат прямо в родителе.
 */
export function WebvisorPrivate({ children }: { children: ReactNode }) {
	// Инлайн, а не утилита Tailwind: обёртка обязана исчезнуть из раскладки,
	// даже если класс не попал в сборку CSS.
	return (
		<div className={WEBVISOR_HIDE} style={{ display: "contents" }}>
			{children}
		</div>
	);
}
