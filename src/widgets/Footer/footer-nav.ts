/**
 * Состав нижней навигации.
 *
 * Вынесено из компонента по той же причине, что и mobile-menu-links.ts: набор
 * пунктов — это не вёрстка. Он меняется вместе с маршрутами проекта, и искать
 * его среди JSX дороже, чем держать отдельным списком.
 *
 * Все href проверены по app/(frontend) на момент правки: /category,
 * /knowledge, /faq, /contacts, /consents, /profile, /orders, /wishlist,
 * /reviews, /cart.
 *
 * Прежний футер вёл на два несуществующих адреса: /category/all (сегмент
 * [categorySlug] ищет категорию со слагом «all» и отдаёт 404 — «all» это
 * значение фильтра status, а не категория) и /my-reviews (маршрут называется
 * /reviews, как и в мобильном меню). Оба исправлены здесь.
 */

export interface FooterLink {
	label: string;
	href: string;
	/**
	 * Полное название для подсказки. Нужно там, где подпись может не
	 * поместиться в колонку и будет обрезана, — то есть у категорий, которые
	 * приходят из админки и бывают длиной в предложение.
	 */
	title?: string;
	external?: boolean;
	/**
	 * Площадка из настроек сайта. Только у ссылок группы «Мы в сети» — по ней
	 * подбираются знак и фирменный оттенок (src/modules/contact/lib/social-config).
	 */
	platform?: string;
}

export interface FooterGroup {
	/** Заголовок колонки. Короткое слово в верхнем регистре. */
	title: string;
	links: FooterLink[];
}

/**
 * Сколько категорий показываем в колонке «Каталог».
 *
 * Четыре — не «сколько поместится», а сколько читается как подсказка, куда
 * идти. Дальше колонка превращается во второй каталог и перетягивает на себя
 * всю нижнюю навигацию (у мобильного меню то же ограничение, там оно равно
 * восьми — там список и есть главная навигация).
 */
export const MAX_FOOTER_CATEGORIES = 4;

