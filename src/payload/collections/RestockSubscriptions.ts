import type { CollectionConfig } from "payload";
import { isAdminOrSuperAdmin } from "../access/isAdminOrSuperAdmin.ts";
import { ownedByUserOrStaff } from "../access/ownership.ts";

/**
 * «Сообщить о поступлении»: покупатель ждёт, когда товар снова можно будет
 * заказать.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ НЕ ИЗБРАННОЕ
 * ────────────────────────────────────────────────────────────────────────────
 * Избранное — один документ на пользователя с массивом товаров, и у него
 * другой смысл: «отложить», а не «позовите, когда появится». Уведомлять всех,
 * кто когда-то отметил товар сердечком, значило бы слать то, о чём не
 * просили, а снятие сердечка молча отменяло бы ожидание. К тому же главный
 * запрос здесь — «кто ждёт товар X» — по массиву внутри документов делается
 * только перебором.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ЖИЗНЕННЫЙ ЦИКЛ
 * ────────────────────────────────────────────────────────────────────────────
 * Строка существует ровно пока подписка активна. Когда товар возвращается в
 * продажу, воркер (modules/restock) ОДНИМ запросом удаляет пачку подписок и
 * создаёт по уведомлению на каждую удалённую — см. restock-subscriptions.db.ts.
 * Поэтому повтор задачи после сбоя не даёт второго уведомления: те, кого уже
 * уведомили, в таблице больше не лежат. Статус «уведомлён» не нужен — факт
 * уведомления живёт в самом уведомлении.
 *
 * Пара (пользователь, товар) уникальна на уровне базы: повторное нажатие
 * «Сообщить о поступлении» — это `ON CONFLICT DO NOTHING`, а не дубль.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ДОСТУП
 * ────────────────────────────────────────────────────────────────────────────
 * Создание и удаление — только через server actions modules/restock с
 * overrideAccess: владелец подставляется из сессии, а товар проверяется на
 * то, что его действительно нельзя купить. Прямой REST закрыт.
 */
export const RestockSubscriptions: CollectionConfig = {
	slug: "restock-subscriptions",
	labels: {
		singular: "Ожидание поступления",
		plural: "Ожидают поступления",
	},

	admin: {
		useAsTitle: "id",
		defaultColumns: ["product", "user", "createdAt"],
		group: "Магазин",
		description:
			"Покупатели, которые попросили сообщить о поступлении товара. " +
			"Запись удаляется, когда покупатель получил уведомление.",
	},

	access: {
		read: ownedByUserOrStaff,
		create: () => false,
		update: () => false,
		delete: isAdminOrSuperAdmin,
	},

	fields: [
		{
			name: "user",
			type: "relationship",
			relationTo: "users",
			required: true,
			index: true,
			label: "Покупатель",
		},
		{
			name: "product",
			type: "relationship",
			relationTo: "products",
			required: true,
			index: true,
			label: "Товар",
		},
	],

	indexes: [
		{
			fields: ["user", "product"],
			unique: true,
		},
	],
};
