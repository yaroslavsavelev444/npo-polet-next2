/** Что статье нужно от окружения: id загруженных картинок и найденных товаров. */
export type SeedResolve = {
	/** Картинка из папки статьи; подпись — из `images` описания статьи. */
	img: (name: string) => LexicalNode;
	/**
	 * Ссылка на карточку товара. Если товара с таким slug на сайте нет
	 * (или он не опубликован) — просто текст: битая ссылка хуже никакой.
	 */
	product: (slug: string, text: string) => Inline;
};

