/** Команды CLI — по одной на строку, как их вводят. */
function cli(...commands: string[]): LexicalNode {
	return p(
		...commands.flatMap((command, index) =>
			index === 0
				? [code(command)]
				: [{ type: "linebreak", version: 1 }, code(command)],
		),
	);
}

