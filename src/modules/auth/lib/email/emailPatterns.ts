/**
 * Регулярные выражения для проверки email, вынесенные отдельно от логики
 * валидатора. Новое правило-паттерн можно добавить здесь, не трогая
 * emailValidator.ts.
 */

/**
 * Метка домена: буква или цифра по краям, дефисы допустимы только внутри.
 * `\p{L}`, а не `[a-z]`, — чтобы не отбрасывать интернационализированные
 * домены, записанные не в punycode (например «почта.рф»).
 */
const DOMAIN_LABEL = "[\\p{L}\\p{N}](?:[\\p{L}\\p{N}-]{0,61}[\\p{L}\\p{N}])?";

/**
 * Проверка синтаксиса email.
 *
 * Домен проверяется по-настоящему — минимум одна метка, точка, буквенная
 * зона верхнего уровня от двух знаков. Раньше здесь стоял `[^\s@]+\.[^\s@]+`,
 * и этого хватало: «строгую проверку домена» делал allowlist российских
 * почтовых сервисов. Allowlist удалён (регистрация открыта для любой
 * почты), поэтому проверка формы домена обязана жить здесь — иначе
 * «user@-mail..c» проходил бы регистрацию.
 *
 * Local-part по-прежнему проверяется мягко (RFC 5322 разрешает в ней почти
 * всё, включая кавычки и спецсимволы), но не допускает точку по краям —
 * такой адрес не принимает ни один почтовый сервер.
 */
export const EMAIL_FORMAT_REGEX = new RegExp(
	`^[^\\s@.](?:[^\\s@]*[^\\s@.])?@(?:${DOMAIN_LABEL}\\.)+\\p{L}{2,63}$`,
	"u",
);

/**
 * Паттерны local-part (до «@»), характерные для автоматических QA/скриптов
 * и сканеров, а не для реальных пользователей. Проверяется ТОЛЬКО полное
 * совпадение (с учётом опциональных цифр/пробела в известных местах), чтобы не
 * ловить ложные срабатывания на живых именах вроде «testosterone» или
 * «contest2024».
 *
 * Список составлен по факту наблюдавшихся адресов: testuser1234, test123,
 * dupetest, lockouttest, errortest, finalcheck и т.п.
 */
export const SUSPICIOUS_LOCAL_PART_PATTERNS: readonly RegExp[] = [
	/^testuser\d*$/i,
	/^test\d+$/i,
	/^dupe ?test\d*$/i,
	/^duplicate ?test\d*$/i,
	/^lockout ?test\d*$/i,
	/^error ?test\d*$/i,
	/^final ?check\d*$/i,
	/^final ?test\d*$/i,
	/^qa ?test\d*$/i,
	/^sanity ?check\d*$/i,
	/^smoke ?test\d*$/i,
	/^automation ?test\d*$/i,
];

export const hasSuspiciousLocalPart = (localPart: string): boolean => {
	const normalized = localPart.trim();
	return SUSPICIOUS_LOCAL_PART_PATTERNS.some((re) => re.test(normalized));
};
