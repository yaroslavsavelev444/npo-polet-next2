"use server";

import { getPayloadInstance } from "@/payload/services/getPayload";
import type { ConsentListItem } from "../types";

/**
 * Согласия, которые показывает форма регистрации.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ОТДЕЛЬНОЕ ДЕЙСТВИЕ, ЕСЛИ СТРАНИЦА РЕГИСТРАЦИИ ГРУЗИТ ИХ САМА
 * ────────────────────────────────────────────────────────────────────────────
 * Страница — серверный компонент и читает список при рендере. Оверлей поверх
 * корзины так не может: он живёт в клиентском дереве шапки, которая
 * присутствует на КАЖДОЙ странице витрины. Передать список пропсом значило бы
 * возить документы согласий в RSC-пейлоаде каждой страницы ради окна, которое
 * большинство посетителей не откроет ни разу.
 *
 * Поэтому список подгружается ровно в тот момент, когда человек переключился
 * на шаг регистрации.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТО БЕЗОПАСНО ОТДАВАТЬ БЕЗ АВТОРИЗАЦИИ
 * ────────────────────────────────────────────────────────────────────────────
 * Коллекция `consents` открыта на чтение публично (`read: () => true`) — её
 * тексты и так лежат на /consents, и знать их обязан в том числе тот, кто ещё
 * не зарегистрировался. Персональных данных здесь нет: возвращаются название,
 * версия, признак обязательности и ссылка на документ.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ОТБОР ОБЯЗАН СОВПАДАТЬ С registerAction
 * ────────────────────────────────────────────────────────────────────────────
 * Условия (`isActive` + `needsAcceptance`) повторяют те, по которым
 * registerAction проверяет принятые согласия. Разойдясь, они дали бы отказ
 * регистрации из-за документа, чекбокса которого форма никогда не показывала.
 * Ровно та же пара условий стоит на странице /auth/register.
 */
export async function getRegisterConsentsAction(): Promise<ConsentListItem[]> {
	const payload = await getPayloadInstance();

	const { docs } = await payload.find({
		collection: "consents",
		where: {
			and: [
				{ isActive: { equals: true } },
				{ needsAcceptance: { equals: true } },
			],
		},
		sort: "-isRequired", // Обязательные сначала
		limit: 20,
		depth: 0,
		overrideAccess: true,
	});

	return docs.map((doc) => ({
		id: Number(doc.id),
		slug: doc.slug as string,
		title: doc.title as string,
		version: (doc.version ?? "1.0.0") as string,
		isRequired: (doc.isRequired ?? false) as boolean,
		documentUrl: (doc.documentUrl ?? null) as string | null,
	}));
}
