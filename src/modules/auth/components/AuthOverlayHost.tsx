"use client";

import { useAuthOverlay } from "../store/auth-overlay.store";
import { AuthOverlay } from "./AuthOverlay";

/**
 * Единственная точка отрисовки окна входа.
 *
 * Живёт в шапке (NavbarClientIsland), рядом с CartProvider и по той же
 * причине: шапка присутствует на каждой странице витрины, а окно должно
 * открываться откуда угодно — из панели корзины, со страницы корзины, с
 * оформления, с карточки товара в каталоге.
 *
 * Хост существует отдельно от самого окна ради одного свойства: пока окно
 * закрыто, в дерево не попадает ничего, кроме подписки на один булев флаг.
 * Формы входа и регистрации вместе с их действиями и согласиями не
 * монтируются и не тянут за собой ни состояния, ни эффектов на страницах,
 * где ими никто не пользуется, — а это все страницы витрины.
 */
export function AuthOverlayHost() {
	const isOpen = useAuthOverlay((s) => s.isOpen);

	if (!isOpen) return null;

	return <AuthOverlay />;
}
