import { create } from "zustand";

/**
 * Окно входа поверх текущей страницы — одно на всё приложение.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ГЛОБАЛЬНОЕ СОСТОЯНИЕ
 * ────────────────────────────────────────────────────────────────────────────
 * Открыть окно нужно из мест, между которыми нет никакой общей ветки дерева:
 * панель корзины (живёт в шапке), страница корзины, страница оформления,
 * кнопка «в корзину» на карточке товара в каталоге, кнопка «в избранное».
 * Прокинуть колбэк через все эти пути означало бы протащить проп авторизации
 * через половину витрины.
 *
 * Поэтому здесь — ровно тот же приём, что у панели корзины
 * (modules/cart/store/cart-panel.store.ts): один владелец состояния и один
 * узел отрисовки (AuthOverlayHost в шапке), а вызывающие только просят
 * «открой».
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПРОДОЛЖЕНИЕ — КОЛБЭК, А НЕ «НАМЕРЕНИЕ»
 * ────────────────────────────────────────────────────────────────────────────
 * Напрашивается перечисление поводов (`intent: "checkout" | "wishlist" | …`) и
 * разбор его внутри окна. Это ошибка: тогда модуль авторизации обязан знать
 * про корзину, избранное и оформление — то есть про всё, откуда его зовут, —
 * и каждая новая точка входа правила бы чужой файл.
 *
 * Колбэк разворачивает зависимость: корзина сама говорит, что сделать после
 * входа (перенести гостевую корзину и уйти на оформление), избранное — своё
 * (повторить нажатие на сердечко). Окно про них не знает ничего и только
 * передаёт им id вошедшего покупателя.
 */

/** Что сделать после успешного входа. Ошибка внутри окно не роняет. */
export type AuthOverlayContinuation = (userId: string) => void | Promise<void>;

export type AuthOverlayStep = "login" | "register";

interface AuthOverlayState {
	isOpen: boolean;
	/** С какой формы открывать окно. */
	initialStep: AuthOverlayStep;
	/**
	 * Одна строка о том, зачем нужен вход, — над формой. Пишет её тот, кто
	 * окно открыл: «Войдите, чтобы оформить заказ» и «Войдите, чтобы добавить
	 * товар в избранное» объясняют разное, а безадресное «требуется
	 * авторизация» не объясняет ничего.
	 */
	reason: string | null;
	continuation: AuthOverlayContinuation | null;
	open: (options?: {
		step?: AuthOverlayStep;
		reason?: string;
		onSuccess?: AuthOverlayContinuation;
	}) => void;
	close: () => void;
}

export const useAuthOverlay = create<AuthOverlayState>((set) => ({
	isOpen: false,
	initialStep: "login",
	reason: null,
	continuation: null,

	open: (options = {}) =>
		set({
			isOpen: true,
			initialStep: options.step ?? "login",
			reason: options.reason ?? null,
			continuation: options.onSuccess ?? null,
		}),

	// Продолжение снимается вместе с закрытием: оставленный колбэк выполнился
	// бы при следующем открытии окна — то есть после входа ради избранного
	// человека унесло бы на оформление заказа.
	close: () => set({ isOpen: false, reason: null, continuation: null }),
}));

/**
 * Открыть окно входа из кода, которому не нужен подписчик на состояние
 * (обработчики событий, хуки корзины и избранного).
 *
 * Прямой вызов `useAuthOverlay.getState().open(...)` тоже работает, но через
 * именованную функцию точки входа видны поиском — и видно, что их немного.
 */
export function openAuthOverlay(
	options?: Parameters<AuthOverlayState["open"]>[0],
): void {
	useAuthOverlay.getState().open(options);
}
