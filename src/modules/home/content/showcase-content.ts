/**
 * Моушн-витрина «Как это работает»: тексты, характеристики и раскадровка
 * для каждого изделия.
 *
 * Тексты и цифры перенесены из утверждённых моушн-роликов (по одному на
 * изделие) дословно: это уже согласованная подача, и в коде она не должна
 * расходиться с видео, которое показывают на выставках и в соцсетях.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ВРЕМЯ
 * ────────────────────────────────────────────────────────────────────────────
 * Все отметки — секунды условной шкалы ролика. Прокрутка переводится в эту
 * шкалу линейно, поэтому длина ролика здесь одновременно задаёт и длину
 * прокрутки блока (см. SCROLL_VH_PER_SECOND в MotionShowcase).
 *
 * Каждый такт подаётся последовательно: сначала текст (hold секунд сцена
 * почти стоит, описание набирается), затем действие — текст при этом
 * приглушается. Смотреть одновременно на выстрел и читать характеристику
 * трудно; так зритель делает одно за другим.
 */

export type ShowcaseProductId =
	| "pauk-30bn"
	| "pauk-duplet"
	| "setkomet-fpv"
	| "setkomet-mavic"
	| "vultur-r10"
	| "triple";

/**
 * Значение характеристики. Строка — постоянное; список пар — меняется по
 * ходу ролика: [секунда, значение], действует последнее наступившее.
 */
export type ShowcaseValue = string | ReadonlyArray<readonly [number, string]>;

export interface ShowcaseSpec {
	label: string;
	value: ShowcaseValue;
}

export interface ShowcaseStep {
	title: string;
	text?: string;
	start: number;
	end: number;
	/** Сколько секунд от начала такта отдано тексту до начала действия. */
	hold: number;
}

export interface ShowcaseSloganPart {
	text: string;
	accent?: boolean;
	/** Перенос строки перед этой частью. */
	newline?: boolean;
}

export interface ShowcaseProduct {
	id: ShowcaseProductId;
	/** Полное название — в заголовке ролика. */
	name: string;
	/** Подпись в меню переключения: семейство и модель. */
	menu: readonly [string, string];
	/** Направление: подпись «Принцип работы · …» и группа в меню. */
	category: string;
	duration: number;
	/** До этой секунды на экране крупный титр. */
	introEnd: number;
	steps: ShowcaseStep[];
	/** Колонка характеристик справа на время тактов. */
	specs: ShowcaseSpec[];
	finale: {
		start: number;
		kicker: string;
		/** Крупное название над строкой характеристик (у флагмана). */
		headline?: string;
		specs: Array<{ label: string; value: string }>;
		slogan: ShowcaseSloganPart[];
	};
}

