/** Значение характеристики на секунде t. */
export function resolveValue(value: ShowcaseValue, t: number): string {
	if (typeof value === "string") return value;
	let current = value[0]?.[1] ?? "";
	for (const [at, v] of value) if (t >= at) current = v;
	return current;
}
