export interface ImageManifestEntry {
	src: string;
	/**
	 * Альтернативный текст. Обязателен и пишется здесь, а не в компоненте:
	 * человек, который меняет картинку, должен править описание в той же
	 * строке, иначе alt переживает изображение и начинает врать.
	 */
	alt: string;
	width: number;
	height: number;
	available: boolean;
	/** Что именно должно быть на этом кадре — подсказка для съёмки. */
	brief: string;
}

/**
 * Запись манифеста.
 *
 * width/height — размеры РЕАЛЬНОГО файла, а не пожелание. По ним next/image
 * резервирует место до загрузки и считает srcset; расхождение с файлом даёт
 * либо сдвиг вёрстки, либо размытую картинку.
 *
 * Пропорция файла совпадает с пропорцией блока, в котором он выводится, —
 * за это отвечает scripts/prepare-home-images.py. Поэтому object-fit: cover
 * в вёрстке ничего не обрезает: обрезка уже сделана осознанно, один раз, с
 * выбором того, что в кадре главное.
 */
const image = (
	key: string,
	alt: string,
	brief: string,
	width: number,
	height: number,
): ImageManifestEntry => ({
	src: `/images/home/${key}.jpg`,
	alt,
	width,
	height,
	available: true,
	brief,
});

