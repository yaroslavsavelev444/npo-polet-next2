/**
 * modules/home/lib/media — единственное место, где объявлены пути к медиа
 * главной страницы.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * КУДА КЛАСТЬ ФАЙЛЫ
 * ────────────────────────────────────────────────────────────────────────────
 *   public/videos/hero/hero.webm      — фон первого экрана, десктоп (VP9/AV1)
 *   public/videos/hero/hero.mp4       — то же в H.264 (нужен Safari/iOS)
 *   public/videos/hero/hero-mobile.mp4— короткая версия под вертикальный кадр
 *   public/videos/hero/poster.jpg     — первый кадр, показывается до видео
 *   public/images/home/<ключ>.jpg     — фотографии секций
 *
 * Ни один компонент не знает этих путей: он спрашивает у манифеста ключ.
 * Поэтому переезд медиа в CDN или в Payload — правка одного этого файла.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ФАЙЛА МОЖЕТ НЕ БЫТЬ
 * ────────────────────────────────────────────────────────────────────────────
 * Пока реальные материалы не подложены, компоненты рисуют «слот» — тёмную
 * панель с рамкой и подписью, какой именно файл сюда нужен (см. MediaSlot).
 * Это намеренно: пустое место, которое честно говорит, чего не хватает,
 * лучше стокового кадра, который потом забудут заменить.
 *
 * Хранить признак «файл есть» приходится флагом, а не проверкой файловой
 * системы: манифест читается и на клиенте, где fs недоступен, а обращаться к
 * несуществующему файлу за 404 на каждый рендер — хуже, чем объявить правду
 * один раз.
 */

export interface VideoSource {
	/** Порядок важен: браузер берёт первый поддерживаемый. */
	src: string;
	type: string;
}

export interface HeroVideoManifest {
	/** false — файлов ещё нет, показывается статичный первый экран. */
	available: boolean;
	sources: VideoSource[];
	/** Отдельный, более лёгкий файл для узких экранов. */
	mobileSources: VideoSource[];
	poster: string | null;
	/**
	 * Соотношение сторон постера. Нужно, чтобы зарезервировать место до
	 * загрузки и не получить сдвиг вёрстки.
	 */
	posterAspect: number;
}

