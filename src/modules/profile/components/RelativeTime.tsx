"use client";

import { useEffect, useState } from "react";
import { formatDateTime, formatRelative } from "../lib/format";

/**
 * Время в относительной шкале («5 минут назад»), с абсолютным значением в
 * подсказке.
 *
 * ПОЧЕМУ НЕ СРАЗУ ОТНОСИТЕЛЬНОЕ. Относительное значение считается от «сейчас»,
 * а «сейчас» на сервере и на клиенте разное: между отрисовкой ответа и
 * гидратацией проходят сотни миллисекунд, и на границе минуты сервер напишет
 * «только что», а клиент — «1 минуту назад». React считает это расхождением
 * разметки и ругается в консоль, а в строгом режиме перерисовывает поддерево.
 *
 * Поэтому первый клиентский проход совпадает с серверным (абсолютная дата), и
 * только после монтирования значение заменяется относительным. Подмена
 * происходит в том же кадре, что и остальная гидратация, — визуально это
 * одно состояние.
 *
 * Живого пересчёта по таймеру здесь нет намеренно: список устройств смотрят
 * секунды, а таймер на каждой строке — это работа в фоне ради значения,
 * которое всё равно обновится при следующем «Обновить».
 */
export function RelativeTime({ iso }: { iso: string }) {
	const [mounted, setMounted] = useState(false);
	useEffect(() => setMounted(true), []);

	const absolute = formatDateTime(iso);

	return (
		<time dateTime={iso} title={absolute}>
			{mounted ? formatRelative(iso) : absolute}
		</time>
	);
}

export default RelativeTime;
