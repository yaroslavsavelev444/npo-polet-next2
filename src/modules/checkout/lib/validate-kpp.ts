/**
 * КПП: 9 знаков — код налогового органа (4 цифры), причина постановки на
 * учёт (2 знака: цифры или заглавные латинские буквы) и номер (3 цифры).
 * Контрольной суммы у КПП нет, поэтому проверяется только формат.
 *
 * Поле необязательное: у ИП КПП нет, а ручной ввод без него должен работать
 * как раньше. Пустое значение — не ошибка.
 */
export function validateKpp(raw: string): string | null {
	const kpp = raw.trim().replace(/\s/g, "").toUpperCase();
	if (!kpp) return null;
	if (kpp.length !== 9) return "КПП должен содержать 9 знаков";
	if (!/^\d{4}[\dA-Z]{2}\d{3}$/.test(kpp)) return "Неверный формат КПП";
	return null;
}
