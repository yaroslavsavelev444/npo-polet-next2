import {
	type BreadcrumbItem,
	Breadcrumbs,
} from "@/components/Breadcrumbs/Breadcrumbs";
import { Reveal, RevealLines } from "@/shared/components/motion/Reveal";
import { PageContainer } from "@/shared/components/PageContainer";

interface CategoryCatalogHeroProps {
	/** Заголовок, разбитый на строки вручную — см. комментарий ниже. */
	titleLines: string[];
	lead: string;
	breadcrumbs: BreadcrumbItem[];
}

/**
 * Первый экран витрины каталога.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПОЛНОШИРИННАЯ ТЁМНАЯ ПОЛОСА, А НЕ ШАПКА КАК У РАЗДЕЛА
 * ────────────────────────────────────────────────────────────────────────────
 * Страница раздела — вторая ступень: на неё приходят из каталога или из
 * поиска, уже зная, что ищут, и её шапка правильно сделана тихой. Витрина
 * каталога — точка входа наравне с главной и контактами, и в общей навигации
 * сайта она обязана иметь такой же вес.
 *
 * Материал взят у первого экрана контактов, вплоть до источника света:
 * подложка --void-deep (темнее витрины — полноэкранная секция может быть
 * темнее страницы, карточка не может), один сдержанный радиальный источник
 * снизу слева, из-под заголовка. Этот приём связывает страницы надёжнее
 * любого повторённого элемента: он же держит первый экран главной, пока не
 * загрузилось видео.
 *
 * Мера ширины — общий PageContainer, тот же, что у сетки ниже. Это не
 * формальность: заголовок и левый край первой карточки обязаны стоять на
 * одной вертикали, иначе страница читается как два сложенных макета.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ЗАГОЛОВОК
 * ────────────────────────────────────────────────────────────────────────────
 * Набран акцидентной PaluiSP2 (.u-display поднимает регистр и включает
 * словарный перенос) — как названия разделов, пункты мобильного меню и
 * первый экран контактов.
 *
 * Строки разбиты вручную, а не отданы переносу: у этой гарнитуры знак
 * занимает ~1.2em, и автоматический перенос на узком экране оставлял бы в
 * первой строке одно слово из двух, а на широком собирал бы обе в одну
 * строку длиной в экран. Ручная разбивка даёт одинаковый двухстрочный блок
 * на любой ширине.
 *
 * Границы кегля выведены из самого длинного слова, а не подобраны на глаз.
 * «ПРОДУКЦИИ» при letter-spacing -0.005em занимает 10.83em (замер в браузере,
 * не оценка):
 *
 *   — нижняя (1.625rem = 26px) даёт 282px при 288, доступных на экране 320px
 *     за вычетом полей контейнера;
 *   — верхняя (4.25rem = 68px) — 736px при 800px колонки заголовка в
 *     двухколоночной раскладке (контейнер 1232 минус колонка пояснения 384 и
 *     отбивка 48).
 *
 * Меняя текст заголовка, оба предела нужно пересчитать: слово, вылезшее за
 * колонку, здесь не обрежется и не переполнит её, а молча уедет в перенос по
 * слогам («ПРОДУК-ЦИИ») — hyphens: auto включён в .u-display ради длинных
 * названий разделов.
 *
 * Вторая колонка появляется с 1280px, а не с 1024: на 1024 за вычетом
 * пояснения колонке заголовка остаётся 496px, куда 10.83em не помещаются ни
 * при каком читаемом кегле. До этой ширины пояснение идёт под заголовком, и
 * заголовок получает весь контейнер.
 *
 * Появление построчное (RevealLines): текст лежит в DOM ровно один раз
 * обычными узлами внутри <h1>, поэтому ни поисковику, ни скринридеру каскад
 * не мешает. При prefers-reduced-motion строки просто видны (см. секцию в
 * home.css).
 */
export function CategoryCatalogHero({
	titleLines,
	lead,
	breadcrumbs,
}: CategoryCatalogHeroProps) {
	return (
		<section
			className="relative isolate overflow-hidden bg-[var(--void-deep)]"
			style={{
				// Шапка сайта — position: fixed, её место в потоке держит
				// HeaderSpacer. Первый экран заезжает ПОД неё (она полупрозрачная
				// с размытием), поэтому спейсер компенсируется отрицательным
				// полем, а содержимое возвращается вниз таким же паддингом.
				marginTop: "calc(-1 * var(--sticky-header-height))",
				paddingTop: "var(--sticky-header-height)",
			}}
		>
			<div
				className="pointer-events-none absolute inset-0 -z-10"
				aria-hidden="true"
				style={{
					background:
						"radial-gradient(110% 70% at 8% 100%, color-mix(in srgb, var(--primary) 13%, transparent) 0%, transparent 58%)",
				}}
			/>

			{/* Разлиновка по нижнему краю полосы: тот же волосяной шов, которым
			    отбиты секции главной. Без него тёмная полоса переходит в витрину
			    ступенькой яркости, и шов приходится додумывать. */}
			<div
				className="pointer-events-none absolute inset-x-0 bottom-0 h-px bg-[var(--rule)]"
				aria-hidden="true"
			/>

			<PageContainer className="flex flex-col pb-[clamp(2.5rem,5vw,4rem)] pt-[clamp(1.5rem,3vw,2.5rem)]">
				<Breadcrumbs items={breadcrumbs} />

				<div className="mt-[clamp(1.5rem,3vw,2.5rem)] flex flex-col gap-[clamp(1.25rem,3vw,3rem)] xl:flex-row xl:items-end xl:gap-[3rem]">
					{/* Заголовку отдана вся оставшаяся ширина, пояснению — колонка
					    фиксированной меры. При свободном распределении flex делил
					    бы ряд по содержимому, и колонка заголовка оказывалась бы
					    уже самого длинного слова — тогда оно уходит в перенос по
					    слогам там, где помещается целиком. Тот же приём, что в
					    шапке раздела. */}
					<h1 className="u-display min-w-0 flex-1 text-[clamp(1.625rem,0.6rem+4.4vw,4.25rem)] leading-[0.96] text-[var(--text-primary)]">
						<RevealLines lines={titleLines} stagger={120} />
					</h1>

					<Reveal delay={260}>
						{/* Пояснение прижато к нижней линии заголовка: у капители
						    PaluiSP2 верх строки на глаз выше, чем у Manrope, и
						    выравнивание по верху давало заметный уступ. */}
						<p className="max-w-[52ch] text-[0.9375rem] leading-[1.6] text-[var(--text-secondary)] xl:w-[24rem] xl:shrink-0">
							{lead}
						</p>
					</Reveal>
				</div>
			</PageContainer>
		</section>
	);
}

export default CategoryCatalogHero;
