"use client";

/**
 * Отметка «этот заказ только что оформлен».
 *
 * ════════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОНА ВООБЩЕ НУЖНА
 * ════════════════════════════════════════════════════════════════════════════
 * Адрес /orders/[orderNumber] — это не «страница спасибо», а страница заказа:
 * на неё ведёт ссылка из «Моих заказов», на неё возвращаются через месяц,
 * чтобы посмотреть трек-номер, и на неё попадают по прямой ссылке. Праздновать
 * при каждом таком открытии нельзя: конфетти над заказом, который отменили в
 * прошлый вторник, — это не радость, а поломка.
 *
 * Праздник принадлежит СОБЫТИЮ, а не адресу. Поэтому оформление заказа
 * оставляет одноразовую отметку, а страница её забирает: конфетти взлетает
 * ровно один раз — в тот переход, который его заслужил.
 *
 * ════════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ sessionStorage, А НЕ ПАРАМЕТР В АДРЕСЕ
 * ════════════════════════════════════════════════════════════════════════════
 * Параметр `?created=1` пришлось бы вычищать из адреса вручную, он пережил бы
 * перезагрузку (и отпраздновал бы ещё раз), уехал бы в закладку и в чужой чат
 * вместе со ссылкой. Отметка в sessionStorage живёт внутри вкладки, гибнет
 * вместе с ней и исчезает в момент прочтения — три свойства, которых у
 * адресной строки нет ни одного.
 *
 * Цена решения: сервер о празднике не знает, и конфетти запускается после
 * гидратации. Это ровно то, что нужно: страница — серверная и одинаковая для
 * всех, а праздник — добавка поверх неё. Заголовок, номер и статус при этом
 * не зависят от отметки и не мигают.
 *
 * Хранилище может быть недоступно (приватный режим, отключённые данные
 * сайта) — тогда праздник просто не состоится, а страница продолжит работать.
 * Ради украшения ничего не должно падать.
 */

const KEY = "orders:just-created";

/** Вызывается оформлением заказа перед переходом на страницу заказа. */
export function markOrderJustCreated(orderNumber: string): void {
	try {
		window.sessionStorage.setItem(KEY, orderNumber);
	} catch {
		// Хранилище недоступно — обойдёмся без конфетти.
	}
}

/**
 * Забирает отметку, если она относится к ЭТОМУ заказу.
 *
 * Именно забирает: повторное чтение вернёт false, поэтому перезагрузка
 * страницы праздник не повторяет. Чужую отметку функция не трогает — человек
 * мог заглянуть в другой заказ по дороге и вернуться к новому.
 */
export function consumeOrderCelebration(orderNumber: string): boolean {
	try {
		if (window.sessionStorage.getItem(KEY) !== orderNumber) return false;
		window.sessionStorage.removeItem(KEY);
		return true;
	} catch {
		return false;
	}
}
