/** Заказ закрыт: движение по сценарию закончилось, этапы показывать нечего. */
export function isTerminalStatus(status: OrderStatus): boolean {
	const tone = ORDER_STATUS_VIEW[status].tone;
	return tone === "done" || tone === "stopped";
}
