/**
 * Склонения и подписи страницы избранного.
 *
 * Отдельный файл, а не функция внутри компонента: те же формы нужны и первому
 * экрану, и липкой панели, и окну подтверждения. Прежняя страница обходилась
 * жёстким «N товаров» и писала «1 товаров» на каждом первом отложенном
 * изделии.
 */

/** «1 товар», «2 товара», «5 товаров». */
export function pluralizeProducts(count: number): string {
	const mod10 = count % 10;
	const mod100 = count % 100;
	if (mod10 === 1 && mod100 !== 11) return "товар";
	if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20))
		return "товара";
	return "товаров";
}

/** «1 позиция», «2 позиции», «5 позиций» — для текста окна подтверждения. */
export function pluralizeItems(count: number): string {
	const mod10 = count % 10;
	const mod100 = count % 100;
	if (mod10 === 1 && mod100 !== 11) return "позицию";
	if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20))
		return "позиции";
	return "позиций";
}

/**
 * Подпись хвоста списка.
 *
 * Согласование по числу обязательно: «Показаны все 1 товар» — это не мелкая
 * небрежность, а первое, что видит покупатель с единственной отложенной
 * позицией. На одной позиции «все» убирается вовсе: сообщать о полноте списка
 * из одного элемента не о чем.
 */
export function tailLabel(count: number): string {
	if (count === 1) return "Показан 1 товар";
	return `Показаны все ${count} ${pluralizeProducts(count)}`;
}
