/**
 * Канонический вид промокода и его денежная арифметика.
 *
 * Нормализация живёт отдельным модулем, потому что её обязаны выполнять ТРИ
 * независимых места одинаково: поле ввода в оформлении заказа, серверное
 * действие и хук коллекции при сохранении кода в админке. Разойдись они хоть
 * в одном символе — администратор завёл бы «summer-24», покупатель ввёл бы
 * «SUMMER-24», и код не нашёлся бы ни по одному запросу.
 */

/**
 * id поля ввода в DOM.
 *
 * Живёт здесь, а не в реестре полей оформления заказа, чтобы зависимость
 * оставалась односторонней: оформление знает о промокодах, промокоды об
 * оформлении — нет. Реестр ошибок формы ссылается на эту константу.
 */
export const PROMO_CODE_INPUT_ID = "checkout-promo-code";

/** Максимальная длина кода. Совпадает с ограничением поля в коллекции. */
export const PROMO_CODE_MAX_LENGTH = 32;
/** Минимальная длина: короче трёх символов код тривиально перебирается. */
export const PROMO_CODE_MIN_LENGTH = 3;

/** Латиница, цифры, дефис и подчёркивание. Кириллица исключена намеренно: */
/* коды печатают на упаковке и диктуют по телефону, и «С» кириллическая от */
/* «C» латинской на слух и на глаз неотличима.                            */
const PROMO_CODE_ALLOWED_RE = /^[A-Z0-9_-]+$/;

/**
 * Приводит введённое значение к каноническому виду.
 *
 * Убираются ВСЕ пробельные символы, а не только по краям: код,
 * скопированный из письма или из мессенджера, регулярно приезжает с
 * неразрывным пробелом внутри или переносом строки на конце.
 */
export function normalizePromoCode(raw: string): string {
	return raw.replace(/\s+/gu, "").toUpperCase();
}

/**
 * Похоже ли значение на промокод.
 *
 * Проверка формы, а не существования: она нужна, чтобы не ходить в базу за
 * заведомо невозможным кодом (и не тратить на него попытку rate limit).
 */
export function isValidPromoCodeFormat(code: string): boolean {
	if (code.length < PROMO_CODE_MIN_LENGTH) return false;
	if (code.length > PROMO_CODE_MAX_LENGTH) return false;
	return PROMO_CODE_ALLOWED_RE.test(code);
}

/**
 * Округление до копеек.
 *
 * Все суммы модуля проходят через него, потому что 0.1 + 0.2 в double даёт
 * 0.30000000000000004: без округления сумма скидки, записанная в заказ,
 * отличалась бы от суммы, показанной покупателю, в последнем знаке.
 */
export function roundMoney(value: number): number {
	return Math.round(value * 100) / 100;
}

const rubFormatter = new Intl.NumberFormat("ru-RU", {
	maximumFractionDigits: 0,
});

/** Сумма для сообщений покупателю: «1 500 ₽». */
export function formatRub(value: number): string {
	return `${rubFormatter.format(Math.round(value))} ₽`;
}
