import { openAuthOverlay } from "@/modules/auth/store/auth-overlay.store";
import { mergeGuestCartIntoAccount } from "../store/cart-panel.store";

/**
 * Переход к оформлению — ОДНА реализация на панель корзины и страницу корзины.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ЧТО ИЗМЕНИЛОСЬ
 * ────────────────────────────────────────────────────────────────────────────
 * Раньше обе кнопки делали `router.push("/auth/login?from=/checkout")`, то
 * есть уводили человека со страницы в момент, когда он уже решил купить.
 * Теперь гость получает окно входа ПОВЕРХ корзины, а состав остаётся на
 * экране. Неавторизованных переходов на /auth/login из пути покупки больше
 * нет ни одного.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПЕРЕНОС КОРЗИНЫ ЖДЁТ ЗДЕСЬ, А НЕ В CartProvider
 * ────────────────────────────────────────────────────────────────────────────
 * CartProvider переносит гостевую корзину сам, эффектом на появление userId
 * (и продолжает это делать — для входа из шапки, с карточки товара и вообще
 * откуда угодно). Но здесь этого недостаточно, и вот почему.
 *
 * Страница /checkout — серверная: она читает корзину ПОЛЬЗОВАТЕЛЯ из базы
 * (buildCheckoutView) и разворачивает в /cart, если та пуста. Эффект же
 * CartProvider сработает только после того, как клиент получит новое дерево с
 * userId, — то есть, вообще говоря, ПОЗЖЕ перехода. В этой гонке гость,
 * только что вошедший ради оформления, попадал бы обратно в корзину: на
 * сервере его позиции ещё в localStorage браузера, а не в базе.
 *
 * Поэтому здесь перенос выполняется явно и дожидается ответа, и только потом
 * происходит переход. Двойной вызов безопасен: mergeGuestCartIntoAccount
 * защищён и от повтора для того же пользователя, и от параллельного запуска.
 */
export interface StartCheckoutOptions {
	/** У гостя корзина локальная — сначала вход, потом перенос. */
	isGuest: boolean;
	/** Навигация вызывающего (router.push) — стор про роутер знать не обязан. */
	navigate: (href: string) => void;
	/** Панель корзины закрывается перед показом окна входа. */
	onBeforeAuth?: () => void;
}

export function startCheckout({
	isGuest,
	navigate,
	onBeforeAuth,
}: StartCheckoutOptions): void {
	if (!isGuest) {
		navigate("/checkout");
		return;
	}

	onBeforeAuth?.();

	openAuthOverlay({
		reason:
			"Заказ оформляется на аккаунт — так вы сможете следить за его статусом и получить счёт. Корзина сохранится.",
		onSuccess: async (userId) => {
			if (userId) {
				await mergeGuestCartIntoAccount(userId);
			}
			navigate("/checkout");
		},
	});
}
