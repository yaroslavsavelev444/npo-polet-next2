// Слова, которыми система баннеров говорит о себе, — в одном месте.
//
// Этот файл читают ТРИ независимых потребителя: конфигурация коллекций Payload
// (варианты select-полей), серверный движок условий и политик, и браузер
// (разметка модалки, отправка событий). Так же устроен `NotificationType` в
// modules/notifications/types.ts — с той разницей, что там список приходится
// дублировать руками, потому что коллекция объявляет опции литералами. Здесь
// зависимость развёрнута в обратную сторону: коллекция строит свои options ИЗ
// этих констант, и разойтись им негде.
//
// ─── Почему подчёркивания, а не дефисы ─────────────────────────────────────
//
// `until_outcome`, `cta_or_dwell` выглядят чужеродно рядом с kebab-case
// остального проекта. Причина в том, что каждое из этих значений попадает в
// `select` коллекции Payload, а Payload строит из любого select имя GraphQL-
// энума, которое обязано подходить под /^[_a-zA-Z][_a-zA-Z0-9]*$/. Дефис
// ломает сборку схемы целиком, и падает при этом код, который в продукте никто
// не вызывает, — то есть дефект доезжает до прода незамеченным.
//
// Правило: ЛЮБОЕ значение, попадающее в `select` Payload, — только буквы,
// цифры и подчёркивание. Значения, живущие лишь в Zod и в БД как текст
// (`BANNER_CLOSE_METHODS`), этого ограничения не имеют.
//
// Здесь ТОЛЬКО словарь и чистые правила над ним: ни обращения к Payload, ни к
// React. Модуль обязан оставаться изоморфным — его импортируют и серверные
// маршруты, и клиентский бандл.

/* ------------------------------------------------------------- контент --- */

/**
 * Как показывается изображение.
 *
 *  * `background` — картинка на всю модалку, текст поверх неё;
 *  * `post`       — картинка отдельным блоком НАД текстом, без наложения.
 *
 * Третьего варианта («без картинки») здесь нет намеренно: отсутствие
 * изображения — это пустое поле `image`, а не режим отображения. Иначе
 * появилась бы пара несовместимых состояний («режим background, картинки
 * нет»), которую каждый читатель разбирал бы самостоятельно.
 */
export const BANNER_IMAGE_MODES = ["background", "post"] as const;
export type BannerImageMode = (typeof BANNER_IMAGE_MODES)[number];

/**
 * Куда ведёт ссылка.
 *
 * Разделение существует не ради admin-формы, а ради двух разных операций в
 * браузере: внутренний адрес открывается роутером Next (`router.push`) без
 * перезагрузки, внешний — новой вкладкой с `rel="noopener noreferrer"`. Одно
 * общее поле `url` означало бы либо перезагрузку приложения на каждой
 * внутренней ссылке, либо `router.push("https://…")`, который молча не
 * сработает.
 */
export const BANNER_LINK_KINDS = ["internal", "external"] as const;
export type BannerLinkKind = (typeof BANNER_LINK_KINDS)[number];

/* --------------------------------------------------------------- показ --- */

/**
 * Политика повторного показа.
 *
 *   once          — «сказать один раз». Объявление, приветствие возможности.
 *   limited       — «повторить, но не больше N раз». Напоминание с потолком.
 *   interval      — «повторять, пока баннер жив». Периодическое напоминание.
 *   until_outcome — «повторять, пока не добьёмся результата». Единственная
 *                   политика, которая смотрит на критерий успеха.
 *
 * `limited` и `interval` не слиты в один вариант с необязательным потолком
 * сознательно: у `interval` потолок тоже есть, но он страховочный, а не
 * смысловой. Слитый вариант заставил бы администратора отвечать «сколько раз»
 * там, где ответ — «сколько понадобится».
 */
export const BANNER_POLICY_KINDS = [
	"once",
	"limited",
	"interval",
	"until_outcome",
] as const;
export type BannerPolicyKind = (typeof BANNER_POLICY_KINDS)[number];

/**
 * Что считается успешным взаимодействием.
 *
 * Нужно только политике `until_outcome`, но хранится у баннера всегда: событие
 * «цель достигнута» полезно в аналитике и для обычных баннеров — именно оно
 * отвечает на вопрос «баннер работает или его просто закрывают».
 */
export const BANNER_OUTCOME_KINDS = ["cta", "dwell", "cta_or_dwell"] as const;
export type BannerOutcomeKind = (typeof BANNER_OUTCOME_KINDS)[number];

/**
 * Важность.
 *
 * Влияет ровно на две вещи, и обе — про очередь, а не про внешний вид:
 * приоритет при выборе следующего баннера и право на повторный показ после
 * мгновенного закрытия. Визуально важный баннер ничем не отличается — иначе
 * администратор начал бы ставить `important` ради оформления, и приоритет
 * перестал бы что-либо значить.
 */
export const BANNER_IMPORTANCE = ["normal", "important"] as const;
export type BannerImportance = (typeof BANNER_IMPORTANCE)[number];

/* ------------------------------------------------------- жизненный цикл --- */

/**
 * Состояние определения баннера — НАМЕРЕНИЕ АДМИНИСТРАТОРА, а не факт показа.
 *
 *   draft     — черновик. Пользователям не виден никогда.
 *   scheduled — «показывать». Виден с момента `publishAt`, не раньше.
 *   paused    — временно снят. Состояние показов сохраняется, поэтому возврат
 *               в `scheduled` не начинает историю заново.
 *   archived  — снят навсегда.
 *
 * `paused` и `archived` — разные состояния, а не одно с флагом: пауза обратима
 * и её отменяют, архив — конец жизни.
 *
 * Отдельного `published` здесь НЕТ, и это отличие от исходной системы стоит
 * объяснить. Там статус переводила фоновая задача по расписанию, а отбор
 * дополнительно сверял `publishAt <= now` — два механизма, из которых второй и
 * был гарантией. В Полёте отбор устроен так же, но воркеров по расписанию нет
 * (единственный worker-контейнер поднимается по профилю и не гарантирован).
 * Задача, которая ничего не охраняет, но требует собственного процесса, — это
 * инфраструктура ради симметрии кода; вместо неё ответ «виден ли он прямо
 * сейчас» считается при чтении документа (поле «Состояние» в админке).
 *
 * Этот же список заменил пару «status + versions.drafts» прежней коллекции:
 * Payload-черновики отвечали на вопрос «готов ли текст», а не «виден ли
 * баннер», и совмещение двух механизмов давало произведение состояний, из
 * которого половина не имела смысла.
 */
export const BANNER_LIFECYCLE_STATUSES = [
	"draft",
	"scheduled",
	"paused",
	"archived",
] as const;
export type BannerLifecycleStatus = (typeof BANNER_LIFECYCLE_STATUSES)[number];

/**
 * Обязательная задержка между «опубликовать» и «виден пользователям».
 *
 * Значение живёт здесь, потому что его читают и хук коллекции (считает
 * `publishAt`), и движок доступности (сверяет `publishAt <= now`), и текст
 * подсказки в админке. Три копии числа — три шанса, что подсказка обещает не
 * то, что делает хук.
 */
export const BANNER_PUBLISH_DELAY_MINUTES = 15;
export const BANNER_PUBLISH_DELAY_MS = BANNER_PUBLISH_DELAY_MINUTES * 60_000;

/* ------------------------------------------------------------ состояние --- */

/**
 * Состояние конкретного баннера у конкретного пользователя.
 *
 * Запись появляется в момент ДОСТАВКИ, а не в момент создания баннера: иначе
 * публикация одного баннера означала бы вставку строки на каждого
 * зарегистрированного пользователя — тысячи строк ради вопроса, ответ на
 * который почти всегда «ещё не показывали».
 *
 *   active    — показан, политика допускает продолжение;
 *   satisfied — цель достигнута, больше не показывать;
 *   exhausted — лимит показов исчерпан либо политика отработала.
 *
 * `satisfied` и `exhausted` разведены, потому что это противоположные исходы с
 * одинаковыми последствиями для показа и РАЗНЫМИ для аналитики: первый
 * означает, что баннер сработал, второй — что он потратил все попытки впустую.
 */
export const BANNER_STATE_STATUSES = [
	"active",
	"satisfied",
	"exhausted",
] as const;
export type BannerStateStatus = (typeof BANNER_STATE_STATUSES)[number];

/* ------------------------------------------------------------- события --- */

/**
 * Значимые события взаимодействия.
 *
 * Список намеренно короткий: каждое событие обязано отвечать на вопрос, ради
 * которого его будут читать. Из «данных ради данных» сюда не попали `hover`,
 * `scroll` и `focus` — по ним невозможно принять ни одного решения о баннере.
 *
 *   delivered  — сервер отдал баннер клиенту. Пишется сервером, не браузером;
 *                разница с `impression` — это «дошло, но не показалось»
 *                (вкладка скрыта, пользователь ушёл, клиент упал).
 *   impression — модалка открылась на экране.
 *   view       — достигнут порог «прочитал». Отдельно от `impression`, потому
 *                что «показали» и «прочитали» — разные факты.
 *   cta        — нажата кнопка действия.
 *   link       — переход по ссылке в тексте (не CTA).
 *   dismiss    — закрытие; способ закрытия в `closeMethod`.
 *   outcome    — зафиксирован успешный результат. Производное событие, и это
 *                осознанно: правило успеха меняется, а история должна
 *                остаться читаемой без пересчёта — «тогда это считалось
 *                успехом».
 */
export const BANNER_EVENT_KINDS = [
	"delivered",
	"impression",
	"view",
	"cta",
	"link",
	"dismiss",
	"outcome",
] as const;
export type BannerEventKind = (typeof BANNER_EVENT_KINDS)[number];

/**
 * Каким способом закрыли модалку.
 *
 * Различие не косметическое: `overlay` и `escape` — это «убрать с дороги», а
 * `close-button` — осознанный отказ. Баннер, который закрывают кликом мимо в
 * 90% случаев, показывается не вовремя; баннер, который закрывают крестиком,
 * не нужен вовсе.
 *
 * `cta` и `link` тоже закрывают модалку — и это НЕ отказ, поэтому у них
 * собственные значения: без них переход по кнопке попадал бы в статистику
 * закрытий и портил бы её ровно на самых удачных показах.
 */
export const BANNER_CLOSE_METHODS = [
	"close-button",
	"overlay",
	"escape",
	"cta",
	"link",
	"navigation",
] as const;
export type BannerCloseMethod = (typeof BANNER_CLOSE_METHODS)[number];

/* --------------------------------------------------------------- ссылки --- */

/**
 * Годится ли адрес для перехода.
 *
 * Проверяется И на сохранении в админке, И перед отдачей клиенту. Двойная
 * проверка здесь не паранойя: документ мог быть создан скриптом, импортирован
 * или отредактирован в обход хука, а результат ошибки — `javascript:`-ссылка,
 * по которой кликает авторизованный пользователь в модалке, показанной нами
 * же.
 *
 * Внутренние адреса — только абсолютный путь от корня. `//evil.example`
 * выглядит как путь и является внешним адресом с протоколом текущей страницы,
 * поэтому вторая косая черта запрещена явно.
 */
export function isSafeBannerHref(kind: BannerLinkKind, href: string): boolean {
	const value = href.trim();
	if (value.length === 0) return false;

	if (kind === "internal") {
		return value.startsWith("/") && !value.startsWith("//");
	}

	try {
		const { protocol } = new URL(value);
		return protocol === "https:" || protocol === "http:";
	} catch {
		return false;
	}
}
