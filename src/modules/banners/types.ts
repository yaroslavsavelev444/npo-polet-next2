import type { BannerCondition, BannerConditionMatch } from "./conditions.ts";
import type {
	BannerImageMode,
	BannerImportance,
	BannerLinkKind,
} from "./vocabulary.ts";

// Баннер в том виде, в каком он уходит в браузер.
//
// Отдельный тип, а не документ Payload, и это та же граница, которую проект
// уже проводит для `NotificationDTO`: наружу уходит ровно то, что нужно
// нарисовать, и ничего сверх.
//
// Что НЕ попадает сюда и почему это важно:
//
//  * СЕРВЕРНЫЕ УСЛОВИЯ. Отправив их, мы рассказали бы каждому авторизованному
//    покупателю, что баннер нацелен на «корзину дороже 20 000, брошенную сутки
//    назад» — то есть выдали бы и сегментацию, и коммерческую логику тому,
//    кому она не адресована. Клиент получает только условия `page`, потому что
//    решать по ним ему и предстоит;
//  * ПОЛИТИКА ПОКАЗА. Сколько раз баннер уже видели и когда покажут снова —
//    решение сервера. У клиента нет ни состояния, ни причин его иметь: он
//    сообщает события, сервер считает;
//  * СЧЁТЧИКИ И ИДЕНТИФИКАТОРЫ ДРУГИХ ПОЛЬЗОВАТЕЛЕЙ.

export type BannerImageView = {
	url: string;
	alt: string;
	width: number | null;
	height: number | null;
	mode: BannerImageMode;
};

export type BannerActionView = {
	label: string;
	href: string;
	kind: BannerLinkKind;
};

export type BannerView = {
	id: number;
	title: string;
	/** Текст. `null` — баннер только с заголовком и картинкой. */
	body: string | null;
	image: BannerImageView | null;
	/** Кнопка действия. `null` — баннер только информирует. */
	cta: BannerActionView | null;
	/** Ссылка в теле, отдельно от кнопки. */
	link: BannerActionView | null;
	importance: BannerImportance;
	/**
	 * Клиентские условия — сейчас только `page`. Пустой массив означает «на
	 * любой странице»; полем `conditionMatch` определяется, обязательны ли они.
	 */
	clientConditions: BannerCondition[];
	conditionMatch: BannerConditionMatch;
	/**
	 * Сколько секунд экранного времени выждать перед показом.
	 *
	 * Отсчитывается клиентом от момента, когда баннер получен, а не от
	 * серверного времени доставки: вкладка могла быть свёрнута, и «через три
	 * минуты после доставки» означало бы «сразу же», когда человек вернётся.
	 */
	delaySeconds: number;
	/** Порог «просмотрено», нужен клиенту, чтобы отправить событие `view`. */
	dwellSeconds: number;
};

/* ------------------------------------------------------------- ответы --- */

/**
 * Ответ `GET /api/banners/next`.
 *
 * `retryAt` — единственное, что клиент знает о темпе показов. Ему незачем
 * знать, что именно его остановило (пауза, суточный предел, пустая очередь);
 * ему нужен один ответ: когда спросить снова и спрашивать ли вообще. `null`
 * означает «сам не спрашивай» — следующий вопрос задаст действие пользователя.
 */
export type NextBannerResponse = {
	banner: BannerView | null;
	/**
	 * Идентификатор показа. Все события взаимодействия ссылаются на него, а не
	 * на пару «пользователь + баннер»: без него два показа одного баннера в
	 * разные дни неразличимы в аналитике, а повторный запрос (перезагрузка
	 * страницы, вторая вкладка) неотличим от настоящего второго показа.
	 */
	impressionId: string | null;
	/** ISO-время следующей осмысленной попытки; `null` — попытки не нужны. */
	retryAt: string | null;
	/**
	 * Есть баннер, который подошёл бы этому человеку на ДРУГОМ экране.
	 *
	 * Единственное, что клиент узнаёт о причинах отказа, и узнаёт не из
	 * любопытства: без этого флага он не знал бы, стоит ли переспрашивать при
	 * переходе по сайту. Оба безусловных варианта плохи — спрашивать на каждой
	 * навигации значит устроить опрос под видом событий, не спрашивать никогда
	 * значит никогда не показать баннер, привязанный к разделу.
	 *
	 * Сегментацию флаг не выдаёт: он говорит «где-то есть подходящий экран», но
	 * ни какой это баннер, ни какой экран, ни по какому признаку человек в него
	 * попал.
	 */
	pageBlocked: boolean;
};

/** Ответ `POST /api/banners/events`. */
export type BannerEventAck = {
	/** Событие записано впервые. `false` у повтора — это не отказ. */
	accepted: boolean;
	/**
	 * Барьер разрешил показ.
	 *
	 * Отдельно от `accepted`, потому что повторный вопрос («не записано, уже
	 * было») — это по-прежнему «можно»: разрешение выдано, и от повторения
	 * вопроса барьер своего мнения не меняет. Один общий флаг заставил бы
	 * клиента выбрасывать баннер при любом ретрае и при каждом двойном вызове
	 * эффекта в React StrictMode.
	 */
	allowed: boolean;
	/** Баннер показывать нельзя — снят, удалён или право на него исчезло. */
	revoked: boolean;
	/** Достигнута ли цель показа этим событием. */
	outcome: boolean;
};
