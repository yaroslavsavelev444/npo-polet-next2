import type { Banner } from "@/payload-types";

// Стартовые сценарии баннеров.
//
// ─── Отбор ─────────────────────────────────────────────────────────────────
//
// Баннер прерывает работу человека, и оправдать это может только повод в
// существующем продукте и проверяемая цель. Поэтому список короткий: пять
// сценариев, у каждого своя задача и свой экран, на который он ведёт.
//
// Что было рассмотрено и ОТБРОШЕНО — это часть отбора:
//
//  * «Добро пожаловать!» после регистрации — ни действия, ни новости, ни
//    причины прерывать работу. Самый частый баннер и самый бесполезный;
//  * «Подтвердите почту» — подтверждение уже встроено в регистрацию кодом из
//    письма, и отдельного экрана «подтвердить сейчас» в продукте нет. Кнопка в
//    никуда хуже отсутствия баннера. Условие `email-verified` при этом
//    оставлено: как только такой экран появится, сценарий соберётся из него;
//  * «У нас скидки» без конкретной скидки — реклама ради рекламы, которая
//    обесценивает канал для случаев, когда сказать действительно есть что.
//    Акционные баннеры создаёт редактор под конкретную акцию, и именно для
//    этого коллекция и нужна;
//  * «Оцените заказ» — в Полёте отзыв пишется на ТОВАР, а не на заказ, и
//    предлагать его имеет смысл тому, у кого право оставить отзыв уже есть.
//    Сценарий ниже построен именно так: не «вы что-то получили», а «есть
//    полученные товары, на которые вы ещё не отозвались».
//
// ─── Почему без изображений ────────────────────────────────────────────────
//
// Картинку выбирает редактор, а не миграция. Сид, создающий документы `media`,
// либо тащит файлы в репозиторий, либо ссылается на чужие адреса — и в обоих
// случаях первое, что делает редактор, это заменяет их. Поле необязательное;
// оба режима отображения («пост» и «фон») проверяются из админки на любом
// баннере.
//
// ─── Пятнадцать минут действуют и здесь ────────────────────────────────────
//
// Сид пишет через Local API, а хуки коллекции при этом выполняются — значит
// засеянные баннеры тоже проходят окно проверки и становятся видны через
// пятнадцать минут. Это не побочный эффект, а нужное поведение: правило, у
// которого есть исключения «для своих», перестаёт быть правилом.

/** Что сид умеет создавать. Подмножество полей коллекции — остальные по умолчанию. */
export type SeedBanner = Pick<
	Banner,
	| "name"
	| "content"
	| "cta"
	| "conditionMatch"
	| "conditions"
	| "importance"
	| "priority"
	| "delaySeconds"
	| "policy"
> & {
	/** Ключ, по которому сид узнаёт свой баннер и не создаёт второй. */
	seedKey: string;
	/** Зачем этот баннер существует. Печатается сидом, в базу не попадает. */
	rationale: string;
};

