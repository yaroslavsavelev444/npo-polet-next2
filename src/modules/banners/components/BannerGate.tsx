import { getCurrentUser } from "@/modules/auth/lib/getCurrentUser";
import { BannerHost } from "./BannerHost";

// Единственное место, где решается, участвует ли вкладка в системе баннеров.
//
// ─── Почему серверная обёртка, а не проверка внутри клиента ────────────────
//
// Баннеры существуют только для авторизованных покупателей. Проверь мы это на
// клиенте, в бандл каждого посетителя уехали бы модалка, выборы ведущей
// вкладки и часы экранного времени — ради того, чтобы ничего не показать.
// Здесь же неавторизованный получает `null`, и клиентского кода в его странице
// не появляется вовсе.
//
// ─── Почему `key` ──────────────────────────────────────────────────────────
//
// Выход и вход — это навигация, а не перезагрузка страницы. Без ключа очередь
// прежнего пользователя пережила бы смену аккаунта: ожидающий показа баннер
// остался бы в памяти вкладки и был бы предъявлен следующему вошедшему с чужим
// `impressionId`. Ключ решает это средствами React, вместо эффекта, который
// сбрасывал бы состояние вручную и на один рендер позже.

export async function BannerGate() {
	const user = await getCurrentUser();

	if (!user) return null;

	return <BannerHost key={user.id} />;
}
