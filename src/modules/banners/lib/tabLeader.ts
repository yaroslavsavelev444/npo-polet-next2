"use client";

// Какая из вкладок показывает баннер.
//
// ─── Задача ────────────────────────────────────────────────────────────────
//
// Баннер принадлежит АККАУНТУ, а не вкладке. Три открытые вкладки без выборов
// означали бы три параллельных запроса за баннером, три показа и три модалки,
// которые человек закрывает по очереди, гадая, сколько ещё осталось. Сервер от
// этого защищён («один баннер в полёте»), но защищён грубо: лишние вкладки
// получали бы отказ, а какая именно покажет — решала бы гонка.
//
// ─── Решение ───────────────────────────────────────────────────────────────
//
// Выборы ведущего через `localStorage`, а не через `BroadcastChannel`. Разница
// принципиальная и в пользу первого: `localStorage` ПЕРЕЖИВАЕТ ЗАКРЫТИЕ
// ВКЛАДКИ-ВЕДУЩЕГО. Ведущий пишет отметку времени раз в две секунды; любая
// вкладка, увидевшая отметку старше шести, забирает лидерство себе. У канала
// такого свойства нет — пришлось бы городить пинги и таймауты поверх него, то
// есть заново изобретать эту же отметку, только без её долговечности.
//
// ─── Видимая вкладка важнее старшей ────────────────────────────────────────
//
// Простые выборы «кто первый, тот и ведущий» дают худший из возможных
// результатов: модалка открывается в свёрнутой вкладке, которую человек открыл
// вчера и забыл. Поэтому в отметке есть флаг видимости, и ВИДИМАЯ ВКЛАДКА
// ЗАБИРАЕТ ЛИДЕРСТВО У СКРЫТОЙ НЕМЕДЛЕННО, не дожидаясь тайм-аута. Обратное
// невозможно: скрытая ждёт полного тайм-аута, иначе две вкладки, переключаемые
// пользователем, отбирали бы лидерство друг у друга по кругу.

const STORAGE_KEY = "polet.banners.leader";

/** Как часто ведущий подтверждает, что жив. */
const HEARTBEAT_MS = 2_000;

/** После какого молчания лидерство считается свободным. */
const STALE_MS = 6_000;

type Claim = {
	id: string;
	at: number;
	visible: boolean;
};

function readClaim(): Claim | null {
	try {
		const raw = localStorage.getItem(STORAGE_KEY);
		if (!raw) return null;

		const claim = JSON.parse(raw) as Partial<Claim>;

		if (typeof claim.id !== "string" || typeof claim.at !== "number") {
			return null;
		}

		return { id: claim.id, at: claim.at, visible: claim.visible === true };
	} catch {
		// Приватный режим, переполненное хранилище, чужой мусор под тем же
		// ключом. Во всех случаях ответ один: считать, что ведущего нет, — тогда
		// вкладка станет ведущей сама и баннеры будут работать, пусть и в каждой
		// вкладке. Это заметно лучше, чем не работать нигде.
		return null;
	}
}

function writeClaim(claim: Claim): void {
	try {
		localStorage.setItem(STORAGE_KEY, JSON.stringify(claim));
	} catch {
		// См. выше: хранилище недоступно. Вкладка продолжит считать себя ведущей
		// по собственной памяти.
	}
}

/**
 * Начать участвовать в выборах.
 *
 * `onChange` вызывается при каждой смене роли — и сразу после подписки, чтобы
 * вызывающему не приходилось отдельно узнавать начальное состояние. Возвращает
 * функцию отписки; она же слагает полномочия, если вкладка была ведущей, —
 * иначе закрытая вкладка держала бы лидерство ещё шесть секунд, и ровно
 * столько же баннеры не показывались бы нигде.
 */
export function electTabLeader(
	onChange: (isLeader: boolean) => void,
): () => void {
	// `crypto.randomUUID` есть во всех браузерах, где работает остальное
	// приложение; запасной вариант — на случай незащищённого контекста, где
	// `crypto` может отсутствовать.
	const id =
		globalThis.crypto?.randomUUID?.() ??
		`tab-${Math.random().toString(36).slice(2)}-${Date.now()}`;

	let leading = false;

	const isVisible = () => document.visibilityState === "visible";

	const announce = (next: boolean) => {
		if (next === leading) return;
		leading = next;
		onChange(leading);
	};

	const tick = () => {
		const claim = readClaim();
		const now = Date.now();
		const visible = isVisible();

		const mine = claim?.id === id;
		const stale = !claim || now - claim.at > STALE_MS;
		// Видимая вкладка отбирает лидерство у скрытой сразу. Скрытая у видимой —
		// никогда: иначе переключение между двумя вкладками превращалось бы в
		// бесконечный обмен лидерством, и модалка мигала бы то там, то тут.
		const preempt = Boolean(claim) && claim?.visible === false && visible;

		if (mine || stale || preempt) {
			writeClaim({ id, at: now, visible });
			announce(true);
			return;
		}

		announce(false);
	};

	// Немедленно, а не через две секунды: единственная вкладка не должна ждать
	// первого тика, чтобы начать показывать баннеры.
	tick();
	const timer = setInterval(tick, HEARTBEAT_MS);

	// Чужая запись в тот же ключ — повод пересчитать роль сразу, не дожидаясь
	// тика. Это то, что делает передачу лидерства мгновенной при открытии новой
	// вкладки.
	const onStorage = (event: StorageEvent) => {
		if (event.key === STORAGE_KEY) tick();
	};

	// Переключились на эту вкладку — она вправе забрать лидерство немедленно.
	const onVisibility = () => tick();

	window.addEventListener("storage", onStorage);
	document.addEventListener("visibilitychange", onVisibility);

	return () => {
		window.removeEventListener("storage", onStorage);
		document.removeEventListener("visibilitychange", onVisibility);
		clearInterval(timer);

		// Слагаем полномочия, но только свои: за время работы лидерство могло
		// уйти к другой вкладке, и стирать её запись значило бы устроить новые
		// выборы на ровном месте.
		if (leading && readClaim()?.id === id) {
			try {
				localStorage.removeItem(STORAGE_KEY);
			} catch {
				// Нечего делать: следующая вкладка дождётся истечения отметки.
			}
		}
	};
}
